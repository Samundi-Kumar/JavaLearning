package day01;

public class Arithmetic {
    public static void main(String[] args){
        int a = 10;
        int b = 5;

        System.out.println(a + b);
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a/ b);
        System.out.println(a % b);

        //RELATIONAL OPERATOR

        System.out.println(a == b);
        System.out.println(a != b);
        System.out.println(a < b);
        System.out.println(a > b);
        System.out.println(a <= b);
        System.out.println(b >= a);

        //Unary Operators

        System.out.println(-a);
        System.out.println(++a);
        System.out.println(a++);
        System.out.println(--a);
        System.out.println(a--);


    }



}
